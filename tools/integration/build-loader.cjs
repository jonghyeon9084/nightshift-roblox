'use strict';
// Generates a deterministic Edit-only installer. No Studio or network side effects.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..');
const manifest=[
 ['src/server/Main.server.luau','ServerScriptService.NightShift.Main','Script'],
 ['src/client/Main.client.luau','StarterPlayer.StarterPlayerScripts.NightShift.Main','LocalScript'],
];
// Top-level production modules only; never install test fixtures or validation bundles.
for(const [directory,target] of [['src/shared','ReplicatedStorage.NightShift.Shared'],['tools/world','ServerStorage.NightShift'],['tools/advertising','ServerStorage.NightShift']]){
 for(const name of fs.readdirSync(path.join(root,directory)).filter(n=>n.endsWith('.luau')&&(directory==='src/shared'||/^Build/.test(n))).sort())
  manifest.push([`${directory}/${name}`,`${target}.${name.slice(0,-5)}`,'ModuleScript']);
}
for(const side of ['server','client']){
 const dir=`src/${side}/Modules`;
 const target=side==='server'?'ServerScriptService.NightShift.Modules':'StarterPlayer.StarterPlayerScripts.NightShift.Modules';
 for(const name of fs.readdirSync(path.join(root,dir)).filter(n=>n.endsWith('.luau')).sort()) manifest.push([`${dir}/${name}`,`${target}.${name.slice(0,-5)}`,'ModuleScript']);
}
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const luaString=s=>{let eq='=';while(s.includes(']'+eq+']'))eq+='=';return '['+eq+'['+s+']'+eq+']';};
const entries=manifest.map(([file,target,className])=>{const source=fs.readFileSync(path.join(root,file),'utf8');return {file,target,className,source,sha256:hash(source)};});
if(new Set(entries.map(e=>e.target)).size!==entries.length)throw Error('Duplicate installer destination');
const worldSources=new Set(entries.filter(e=>/^(tools\/(world|advertising)|src\/shared)\//.test(e.file)).map(e=>e.file));
const worldHash=hash(entries.filter(e=>worldSources.has(e.file)).map(e=>e.sha256).join(':'));
const prelude=`-- Generated by tools/integration/build-loader.cjs. Edit only; NightShift namespace only.
assert(not game:GetService("RunService"):IsRunning(), "Stop Play before installing NightShift")
local rows = {
${entries.map(e=>` {Path=${luaString(e.target)}, Class=${luaString(e.className)}, Hash=${luaString(e.sha256)}, Source=${luaString(e.source)}},`).join('\n')}
}
local function child(parent, name)
 local found
 for _, v in ipairs(parent:GetChildren()) do if v.Name == name then assert(not found, "Duplicate path: " .. name) found=v end end
 return found
end
local function resolve(parts, create)
 local node=game:GetService(parts[1])
 for i=2,#parts do
  local name=parts[i]
  local nextNode=child(node,name)
  if nextNode then
   if name=="StarterPlayerScripts" and i==2 then assert(nextNode:IsA("StarterPlayerScripts"), "Wrong StarterPlayerScripts type")
   else assert(nextNode:IsA("Folder") and nextNode:GetAttribute("NightShiftOwned")==true, "Unowned/type-conflicting namespace: " .. nextNode:GetFullName()) end
  elseif create then
   assert(name~="StarterPlayerScripts", "StarterPlayerScripts missing")
   nextNode=Instance.new("Folder") nextNode.Name=name nextNode:SetAttribute("NightShiftOwned",true) nextNode.Parent=node
  else return nil end
  node=nextNode
 end
 return node
end
-- Validate all existing destinations before any writes. Never adopt arbitrary same-name content.
for _, row in ipairs(rows) do
 local parts=string.split(row.Path,".") local name=table.remove(parts)
 local parent=resolve(parts,false) local old=parent and child(parent,name)
 if old then assert(old.ClassName==row.Class and old:GetAttribute("NightShiftOwned")==true,"Unowned source collision: " .. row.Path) end
end
local oldWorld=child(workspace,"NightShiftWorld")
if oldWorld then assert(oldWorld:IsA("Model") and oldWorld:GetAttribute("NightShiftOwned")==true,"Unowned NightShiftWorld collision") end
local changed=0
for _, row in ipairs(rows) do
 local parts=string.split(row.Path,".") local name=table.remove(parts)
 local parent=resolve(parts,true) local old=child(parent,name)
 if not old or old.Source~=row.Source then
  local fresh=Instance.new(row.Class) fresh.Name=name fresh.Source=row.Source
  fresh:SetAttribute("NightShiftOwned",true) fresh:SetAttribute("NightShiftSourceHash",row.Hash)
  if fresh:IsA("BaseScript") then fresh.Enabled=true end
  if old then old:Destroy() end -- Only a validated owned source; replace modules to invalidate require cache.
  fresh.Parent=parent changed+=1
 end
end
local worldHash=${luaString(worldHash)}
local world=oldWorld
if not world or world:GetAttribute("NightShiftSourceHash")~=worldHash then
 local staging=Instance.new("Folder")
 local builder=require(game:GetService("ServerStorage").NightShift.BuildWorld)
 local billboards=require(game:GetService("ServerStorage").NightShift.BuildBillboards)
 local ok, result=pcall(function()
  local candidate=builder.build(staging)
  local ads=billboards.build(candidate)
  assert(ads.Ok, "Billboard installation failed: " .. tostring(ads.Reason or ads.Code))
  local rooftop=require(game:GetService("ServerStorage").NightShift.BuildRooftopBillboards).build(candidate)
  assert(rooftop.Ok, "Rooftop installation failed: " .. tostring(rooftop.Reason or rooftop.Code))
  candidate:SetAttribute("BuildAdUnitCount",ads.AdUnits+rooftop.AdUnits)
  candidate:SetAttribute("NightShiftSourceHash",worldHash)
  -- Validate the completed candidate, including advertising parts in its geometry budget.
  builder.validate(candidate)
  return builder.replaceInEdit(workspace,candidate)
 end)
 if not ok then staging:Destroy() error(result) end
 world=result staging:Destroy()
end
local refreshed=require(game:GetService("ServerStorage").NightShift.BuildBillboards).refreshInWorkspace(world)
assert(refreshed.Ok, "Installed billboard refresh failed")
local rooftop=require(game:GetService("ServerStorage").NightShift.BuildRooftopBillboards).build(world)
assert(rooftop.Ok, "Installed rooftop refresh failed")
return game:GetService("HttpService"):JSONEncode({Installed=#rows,Changed=changed,World=world:GetFullName(),Parts=world:GetAttribute("BuildPartCount"),Lights=world:GetAttribute("BuildLightCount"),AdUnits=world:GetAttribute("BuildAdUnitCount"),Mode="Edit"})
`;
fs.mkdirSync(path.join(root,'.setup/integration'),{recursive:true});
fs.writeFileSync(path.join(root,'.setup/integration/install.luau'),prelude);
fs.writeFileSync(path.join(root,'.setup/integration/manifest.json'),JSON.stringify(entries.map(({source,...entry})=>entry),null,2));
console.log(JSON.stringify({kind:'GENERATED_NOT_INSTALLED',files:entries.length,worldHash,bytes:Buffer.byteLength(prelude)}));
